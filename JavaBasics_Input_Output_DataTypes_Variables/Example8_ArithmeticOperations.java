public class Example8_ArithmeticOperations {
    public static void main(String[] args) {
        int n1 = 10;
        int n2 = 5;
        System.out.println("Addition:- " +  (n1+n2));
        System.out.println("Subtraction:- "+ (n1-n2));
        System.out.println("Multiplication:- "+ (n1*n2));
        System.out.println("Division:- "+ (n1/n2));
        System.out.println("Modulus or Remainder:- " + (n1%n2));
        System.out.println("Pre Increment of n1:- " + ++n1);
        System.out.println("Post Increment of n1:- " + n1++);
        System.out.println(n1);
        System.out.println("Pre decrement of n1:- " + --n2);
        System.out.println("Post decrement of n1:- " + n2--);
        System.out.println(n2);
    }
}
